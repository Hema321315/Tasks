package Javafundamentals;

public class Operatores {
		public static void main(String[] args) { 
		int num = 5; 
		System.out.println(num++);
		System.out.println(++num); 
		int num2 = 8; 
		System.out.println(num2 >> 1);
		System.out.println(num2 << 1);  
		boolean b1 = true, b2 = false; 
		System.out.println(b1 & b2);  
		System.out.println(b1 && b2); 
		} 
}
